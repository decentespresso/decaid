#!/usr/bin/env bash
set -euo pipefail

OUT="${1:?usage: build_ipad_installer.sh <out-dir> <repo-id> [wizard-tag]}"
REPO_ID="${2:?usage: build_ipad_installer.sh <out-dir> <repo-id> [wizard-tag]}"
WIZARD_TAG="${3:-}"
WIZARD_REPO="johnbuckman/SideStepWizard"
TEAM_ID="CDZD6VH5KL"

WORK="$(mktemp -d)"
trap 'hdiutil detach -quiet "$WORK/mnt" 2>/dev/null || true; rm -rf "$WORK"' EXIT

echo "== Download SideStep Wizard ${WIZARD_TAG:-(latest)} =="
gh release download ${WIZARD_TAG:+"$WIZARD_TAG"} --repo "$WIZARD_REPO" -p SideStepWizard.dmg -D "$WORK"
WIZARD_TAG="${WIZARD_TAG:-$(gh release view --repo "$WIZARD_REPO" --json tagName -q .tagName)}"

echo "== Gate 1: dmg notarized and stapled =="
xcrun stapler validate "$WORK/SideStepWizard.dmg"
hdiutil attach -nobrowse -readonly -mountpoint "$WORK/mnt" "$WORK/SideStepWizard.dmg" >/dev/null
WIZARD="$WORK/mnt/SideStepWizard.app"

echo "== Gate 2: Wizard signed by team $TEAM_ID =="
codesign --verify --deep --strict "$WIZARD"
codesign -dv "$WIZARD" 2>&1 | grep -q "TeamIdentifier=$TEAM_ID" \
  || { echo "FAIL: SideStepWizard.app is not signed by team $TEAM_ID"; exit 1; }

echo "== Gate 3: Gatekeeper accepts it as notarized =="
ASSESS="$(spctl -a -vv "$WIZARD" 2>&1 || true)"
echo "$ASSESS"
echo "$ASSESS" | grep -q "source=Notarized Developer ID" \
  || { echo "FAIL: Gatekeeper does not report Notarized Developer ID"; exit 1; }

ID62="$(python3 -c '
import sys
a = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
n, s = int(sys.argv[1]), ""
while n: s, n = a[n % 62] + s, n // 62
print(s or "0")' "$REPO_ID")"
NAME="Decaid installer ($ID62).app"

echo "== Package \"$NAME\" =="
mkdir -p "$WORK/stage" "$OUT/ios"
ditto "$WIZARD" "$WORK/stage/$NAME"
codesign --verify --deep --strict "$WORK/stage/$NAME"
rm -f "$OUT/ios/decaid-ipad-installer.zip"
ditto -c -k --keepParent "$WORK/stage/$NAME" "$OUT/ios/decaid-ipad-installer.zip"

VERSION="$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' "$WIZARD/Contents/Info.plist")"
SHA="$(shasum -a 256 "$OUT/ios/decaid-ipad-installer.zip" | cut -d' ' -f1)"
cat > "$OUT/README.md" <<EOF
# Decaid dist

Generated by \`.github/workflows/ipad-installer.yml\`; do not edit this branch by hand.

## ios/decaid-ipad-installer.zip

Decaid's iPad installer for macOS: the notarized [SideStep Wizard](https://github.com/$WIZARD_REPO/releases/tag/$WIZARD_TAG) $VERSION
(Developer ID team $TEAM_ID), renamed \`$NAME\` so it installs Decaid onto a connected iPad.

- SHA-256: \`$SHA\`
- Built: $(date -u +%Y-%m-%dT%H:%MZ)

Check it yourself after unzipping: \`spctl -a -vv "$NAME"\` reports "Notarized Developer ID".
EOF
echo "== Done: $OUT/ios/decaid-ipad-installer.zip ($SHA) =="
