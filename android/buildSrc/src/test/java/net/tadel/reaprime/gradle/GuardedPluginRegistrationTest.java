package net.tadel.reaprime.gradle;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertThrows;
import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import org.junit.Assume;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

/**
 * The fixture text below is an independent copy of the pinned Flutter 3.47.9 generator output. It is
 * deliberately not built from the production constants so a wrong constant cannot agree with itself.
 */
public class GuardedPluginRegistrationTest {
  @Rule public final TemporaryFolder folder = new TemporaryFolder();

  private static final String PINNED_TEMPLATE =
      "\n"
          + "package io.flutter.plugins;\n"
          + "\n"
          + "import androidx.annotation.Keep;\n"
          + "import androidx.annotation.NonNull;\n"
          + "import io.flutter.Log;\n"
          + "\n"
          + "import io.flutter.embedding.engine.FlutterEngine;\n"
          + "\n"
          + "/**\n"
          + " * Generated file. Do not edit.\n"
          + " * This file is generated by the Flutter tool based on the\n"
          + " * plugins that support the Android platform.\n"
          + " */\n"
          + "@Keep\n"
          + "public final class GeneratedPluginRegistrant {\n"
          + "  private static final String TAG = \"GeneratedPluginRegistrant\";\n"
          + "  public static void registerWith(@NonNull FlutterEngine flutterEngine) {\n"
          + "{{#methodChannelPlugins}}\n"
          + "  {{#supportsEmbeddingV2}}\n"
          + "    try {\n"
          + "      flutterEngine.getPlugins().add(new {{package}}.{{class}}());\n"
          + "    } catch (Exception e) {\n"
          + "      Log.e(TAG, \"Error registering plugin {{name}}, {{package}}.{{class}}\", e);\n"
          + "    }\n"
          + "  {{/supportsEmbeddingV2}}\n"
          + "{{/methodChannelPlugins}}\n"
          + "  }\n"
          + "}\n";

  private static final String HEADER =
      String.join(
          "\n",
          "package io.flutter.plugins;",
          "",
          "import androidx.annotation.Keep;",
          "import androidx.annotation.NonNull;",
          "import io.flutter.Log;",
          "",
          "import io.flutter.embedding.engine.FlutterEngine;",
          "",
          "/**",
          " * Generated file. Do not edit.",
          " * This file is generated by the Flutter tool based on the",
          " * plugins that support the Android platform.",
          " */",
          "@Keep",
          "public final class GeneratedPluginRegistrant {",
          "  private static final String TAG = \"GeneratedPluginRegistrant\";",
          "  public static void registerWith(@NonNull FlutterEngine flutterEngine) {");

  private static final String FOOTER = "  }\n}\n";

  private static final String FIRST_NAME = "battery_plus";
  private static final String FIRST_CLASS = "dev.fluttercommunity.plus.battery.BatteryPlusPlugin";
  private static final String SECOND_NAME = "shared_preferences_android";
  private static final String SECOND_CLASS = "io.flutter.plugins.sharedpreferences.SharedPreferencesPlugin";

  private static String rawRegistrant(String... nameThenClass) {
    StringBuilder source = new StringBuilder(HEADER).append('\n');
    for (int index = 0; index < nameThenClass.length; index += 2) {
      String name = nameThenClass[index];
      String pluginClass = nameThenClass[index + 1];
      source
          .append("    try {\n")
          .append("      flutterEngine.getPlugins().add(new ")
          .append(pluginClass)
          .append("());\n")
          .append("    } catch (Exception e) {\n")
          .append("      Log.e(TAG, \"Error registering plugin ")
          .append(name)
          .append(", ")
          .append(pluginClass)
          .append("\", e);\n")
          .append("    }\n");
    }
    return source.append(FOOTER).toString();
  }

  private static String guardedRegistrant(String... pluginClasses) {
    StringBuilder source = new StringBuilder(HEADER).append('\n');
    for (String pluginClass : pluginClasses) {
      source
          .append("      flutterEngine.getPlugins().add(new ")
          .append(pluginClass)
          .append("());\n");
    }
    return source.append(FOOTER).toString();
  }

  private static final String RAW_TWO =
      rawRegistrant(FIRST_NAME, FIRST_CLASS, SECOND_NAME, SECOND_CLASS);

  private Path flutterSdk(Map<String, String> overrides) throws IOException {
    Path sdk = folder.getRoot().toPath().resolve("flutter-sdk");
    Path versionFile = sdk.resolve("bin/cache/flutter.version.json");
    Files.createDirectories(versionFile.getParent());
    Files.writeString(
        versionFile,
        overrides.getOrDefault(
            "version",
            "{\n"
                + "  \"frameworkVersion\": \"3.47.9\",\n"
                + "  \"channel\": \"stable\",\n"
                + "  \"engineRevision\": \"89c39edfdf\"\n"
                + "}\n"),
        StandardCharsets.UTF_8);
    Path templateFile = sdk.resolve("packages/flutter_tools/lib/src/flutter_plugins.dart");
    Files.createDirectories(templateFile.getParent());
    Files.writeString(
        templateFile,
        overrides.getOrDefault(
            "template",
            "// unrelated\n"
                + "const _androidPluginRegistryTemplateNewEmbedding = '''"
                + PINNED_TEMPLATE
                + "''';\n"
                + "// unrelated tail\n"),
        StandardCharsets.UTF_8);
    return sdk;
  }

  private Path registrant(String content) throws IOException {
    Path directory = Files.createDirectories(folder.getRoot().toPath().resolve("app"));
    Path path = directory.resolve("GeneratedPluginRegistrant.java");
    Files.writeString(path, content, StandardCharsets.UTF_8);
    return path;
  }

  @Test
  public void pinnedTemplateMatchesTheIndependentCopy() {
    assertEquals(PINNED_TEMPLATE, GuardedPluginRegistration.pinnedTemplate());
  }

  @Test
  public void everySwallowedPluginCatchBecomesAPropagatingStatement() {
    GuardedPluginRegistration.Instrumented instrumented =
        GuardedPluginRegistration.instrument(RAW_TWO);

    assertEquals(2, instrumented.pluginCount());
    assertTrue(instrumented.changed());
    assertFalse(instrumented.content().contains("catch (Exception e)"));
    assertFalse(instrumented.content().contains("Log.e(TAG"));
    assertEquals(
        guardedRegistrant(FIRST_CLASS, SECOND_CLASS), instrumented.content());
  }

  @Test
  public void anAlreadyGuardedRegistrantIsLeftByteIdentical() {
    String guarded = guardedRegistrant(FIRST_CLASS, SECOND_CLASS);

    GuardedPluginRegistration.Instrumented instrumented =
        GuardedPluginRegistration.instrument(guarded);

    assertEquals(2, instrumented.pluginCount());
    assertFalse(instrumented.changed());
    assertEquals(guarded, instrumented.content());
  }

  @Test
  public void pluginBlocksAreDerivedFromTheGeneratedInput() {
    String raw =
        rawRegistrant(
            "alpha_plugin",
            "com.example.alpha.AlphaPlugin",
            "beta_plugin",
            "com.example.beta.BetaPlugin",
            "gamma_plugin",
            "com.example.gamma.GammaPlugin");

    GuardedPluginRegistration.Instrumented instrumented =
        GuardedPluginRegistration.instrument(raw);

    assertEquals(3, instrumented.pluginCount());
    assertEquals(
        guardedRegistrant(
            "com.example.alpha.AlphaPlugin",
            "com.example.beta.BetaPlugin",
            "com.example.gamma.GammaPlugin"),
        instrumented.content());
  }

  private static void assertRejected(String content, String expectedFragment) {
    GuardedPluginRegistration.GuardFailure failure =
        assertThrows(
            GuardedPluginRegistration.GuardFailure.class,
            () -> GuardedPluginRegistration.instrument(content));
    assertTrue(
        "expected message containing " + expectedFragment + " but was " + failure.getMessage(),
        failure.getMessage().contains(expectedFragment));
  }

  @Test
  public void partlyInstrumentedInputIsRejected() {
    String partly =
        HEADER
            + "\n"
            + "      flutterEngine.getPlugins().add(new "
            + FIRST_CLASS
            + "());\n"
            + "    try {\n"
            + "      flutterEngine.getPlugins().add(new "
            + SECOND_CLASS
            + "());\n"
            + "    } catch (Exception e) {\n"
            + "      Log.e(TAG, \"Error registering plugin "
            + SECOND_NAME
            + ", "
            + SECOND_CLASS
            + "\", e);\n"
            + "    }\n"
            + FOOTER;

    assertRejected(partly, "partly instrumented");
  }

  @Test
  public void aDifferentCatchShapeIsRejected() {
    String throwableCatch = RAW_TWO.replace("} catch (Exception e) {", "} catch (Throwable e) {");

    assertRejected(throwableCatch, "unsupported plugin block");
  }

  @Test
  public void aNarrowedCatchShapeIsRejected() {
    String runtimeCatch = RAW_TWO.replace("} catch (Exception e) {", "} catch (RuntimeException e) {");

    assertRejected(runtimeCatch, "unsupported plugin block");
  }

  @Test
  public void anUnexpectedBodyStatementIsRejected() {
    String extraStatement =
        RAW_TWO.replace(
            "    try {\n",
            "    Log.d(TAG, \"before registration\");\n    try {\n");

    assertRejected(extraStatement, "unsupported generated registrant body");
  }

  @Test
  public void aLogLineNamingAnotherClassIsRejected() {
    String mismatched =
        RAW_TWO.replace(
            "Log.e(TAG, \"Error registering plugin " + FIRST_NAME + ", " + FIRST_CLASS + "\", e);",
            "Log.e(TAG, \"Error registering plugin "
                + FIRST_NAME
                + ", "
                + SECOND_CLASS
                + "\", e);");

    assertRejected(mismatched, "unsupported plugin block");
  }

  @Test
  public void anUnqualifiedPluginClassIsRejected() {
    String unqualified =
        RAW_TWO.replace("new " + FIRST_CLASS + "()", "new BatteryPlusPlugin()");

    assertRejected(unqualified, "unsupported plugin block");
  }

  @Test
  public void aDuplicatePluginClassIsRejected() {
    String duplicate = rawRegistrant(FIRST_NAME, FIRST_CLASS, FIRST_NAME, FIRST_CLASS);

    assertRejected(duplicate, "duplicate plugin class");
  }

  @Test
  public void anEmptyBodyIsRejected() {
    assertRejected(HEADER + "\n" + FOOTER, "no generated plugin registrations");
  }

  @Test
  public void headerDriftIsRejected() {
    assertRejected(
        RAW_TWO.replace(
            "public final class GeneratedPluginRegistrant {",
            "public final class GeneratedPluginRegistration {"),
        "unsupported generated registrant header");

    assertRejected(
        RAW_TWO.replace(
            "  private static final String TAG = \"GeneratedPluginRegistrant\";\n", ""),
        "unsupported generated registrant header");

    assertRejected(
        RAW_TWO.replace(
            "public static void registerWith(@NonNull FlutterEngine flutterEngine) {",
            "public static void register(@NonNull FlutterEngine flutterEngine) {"),
        "unsupported generated registrant header");
  }

  @Test
  public void footerDriftIsRejected() {
    assertRejected(RAW_TWO + "\n", "unsupported generated registrant footer");
    assertRejected(RAW_TWO.replace(FOOTER, "  }\n}\n\n"), "unsupported generated registrant footer");
  }

  @Test
  public void aRegistrantThatIsNotJavaSourceIsRejected() {
    assertRejected("not a generated registrant", "unsupported generated registrant header");
  }

  @Test
  public void aMissingRegistrantFailsTheBuild() throws IOException {
    Path sdk = flutterSdk(Map.of());
    Path missing = folder.getRoot().toPath().resolve("absent/GeneratedPluginRegistrant.java");

    GuardedPluginRegistration.GuardFailure failure =
        assertThrows(
            GuardedPluginRegistration.GuardFailure.class,
            () -> GuardedPluginRegistration.guard(missing, sdk));

    assertTrue(failure.getMessage(), failure.getMessage().contains("generated registrant is missing"));
  }

  @Test
  public void aRegistrantThatIsNotUtf8FailsTheBuild() throws IOException {
    Path sdk = flutterSdk(Map.of());
    Path path = folder.getRoot().toPath().resolve("GeneratedPluginRegistrant.java");
    Files.write(path, new byte[] {(byte) 0xff, (byte) 0xfe, 'x'});

    GuardedPluginRegistration.GuardFailure failure =
        assertThrows(
            GuardedPluginRegistration.GuardFailure.class,
            () -> GuardedPluginRegistration.guard(path, sdk));

    assertTrue(failure.getMessage(), failure.getMessage().contains("not readable UTF-8"));
  }

  @Test
  public void anUnsupportedFlutterVersionFailsTheBuild() throws IOException {
    Path sdk =
        flutterSdk(Map.of("version", "{\n  \"frameworkVersion\": \"3.50.1\"\n}\n"));

    GuardedPluginRegistration.GuardFailure failure =
        assertThrows(
            GuardedPluginRegistration.GuardFailure.class,
            () -> GuardedPluginRegistration.verifyFlutterSdk(sdk));

    assertTrue(failure.getMessage(), failure.getMessage().contains("3.50.1"));
    assertTrue(failure.getMessage(), failure.getMessage().contains("3.47.9"));
  }

  @Test
  public void aMissingFlutterVersionFileFailsTheBuild() throws IOException {
    Path sdk = folder.getRoot().toPath().resolve("empty-sdk");

    GuardedPluginRegistration.GuardFailure failure =
        assertThrows(
            GuardedPluginRegistration.GuardFailure.class,
            () -> GuardedPluginRegistration.verifyFlutterSdk(sdk));

    assertTrue(failure.getMessage(), failure.getMessage().contains("flutter.version.json"));
  }

  @Test
  public void aChangedGeneratorTemplateFailsTheBuild() throws IOException {
    String drifted =
        PINNED_TEMPLATE.replace("} catch (Exception e) {", "} catch (Throwable e) {");
    Path sdk =
        flutterSdk(
            Map.of(
                "template",
                "const _androidPluginRegistryTemplateNewEmbedding = '''" + drifted + "''';\n"));

    GuardedPluginRegistration.GuardFailure failure =
        assertThrows(
            GuardedPluginRegistration.GuardFailure.class,
            () -> GuardedPluginRegistration.verifyFlutterSdk(sdk));

    assertTrue(failure.getMessage(), failure.getMessage().contains("template"));
  }

  @Test
  public void aMissingGeneratorTemplateFailsTheBuild() throws IOException {
    Path sdk = folder.getRoot().toPath().resolve("sdk-without-tools");
    Path versionFile = sdk.resolve("bin/cache/flutter.version.json");
    Files.createDirectories(versionFile.getParent());
    Files.writeString(versionFile, "{\"frameworkVersion\": \"3.47.9\"}\n", StandardCharsets.UTF_8);

    GuardedPluginRegistration.GuardFailure failure =
        assertThrows(
            GuardedPluginRegistration.GuardFailure.class,
            () -> GuardedPluginRegistration.verifyFlutterSdk(sdk));

    assertTrue(failure.getMessage(), failure.getMessage().contains("flutter_plugins.dart"));
  }

  @Test
  public void guardRewritesTheRegistrantInPlaceIdempotently() throws IOException {
    Path sdk = flutterSdk(Map.of());
    Path path = registrant(RAW_TWO);

    int firstCount = GuardedPluginRegistration.guard(path, sdk);
    String firstPass = Files.readString(path, StandardCharsets.UTF_8);

    int secondCount = GuardedPluginRegistration.guard(path, sdk);
    String secondPass = Files.readString(path, StandardCharsets.UTF_8);

    assertEquals(2, firstCount);
    assertEquals(2, secondCount);
    assertEquals(guardedRegistrant(FIRST_CLASS, SECOND_CLASS), firstPass);
    assertEquals(firstPass, secondPass);
    try (var entries = Files.list(path.getParent())) {
      assertEquals(
          List.of("GeneratedPluginRegistrant.java"),
          entries.map(entry -> entry.getFileName().toString()).toList());
    }
  }

  @Test
  public void aRegeneratedRawRegistrantIsInstrumentedAgain() throws IOException {
    Path sdk = flutterSdk(Map.of());
    Path path = registrant(RAW_TWO);
    GuardedPluginRegistration.guard(path, sdk);

    Files.writeString(path, rawRegistrant(SECOND_NAME, SECOND_CLASS), StandardCharsets.UTF_8);
    int count = GuardedPluginRegistration.guard(path, sdk);

    assertEquals(1, count);
    assertEquals(guardedRegistrant(SECOND_CLASS), Files.readString(path, StandardCharsets.UTF_8));
  }

  @Test
  public void malformedInputLeavesTheRegistrantUntouched() throws IOException {
    Path sdk = flutterSdk(Map.of());
    String malformed = RAW_TWO.replace("} catch (Exception e) {", "} catch (Error e) {");
    Path path = registrant(malformed);

    assertThrows(
        GuardedPluginRegistration.GuardFailure.class,
        () -> GuardedPluginRegistration.guard(path, sdk));

    assertEquals(malformed, Files.readString(path, StandardCharsets.UTF_8));
  }

  @Test
  public void theInstalledPinnedSdkMatchesTheGuard() {
    String flutterRoot = System.getenv("FLUTTER_ROOT");
    Assume.assumeTrue("FLUTTER_ROOT is not set", flutterRoot != null && !flutterRoot.isEmpty());
    Path sdk = Path.of(flutterRoot);
    Assume.assumeTrue("not the pinned SDK", Files.exists(sdk.resolve("bin/cache/flutter.version.json")));

    GuardedPluginRegistration.verifyFlutterSdk(sdk);
  }
}
