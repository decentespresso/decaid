package net.tadel.reaprime.gradle;

import java.io.IOException;
import java.nio.charset.MalformedInputException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Turns Flutter's generated Android plugin registrant into a registrant whose caller can observe failure.
 *
 * <p>The pinned generator wraps every plugin in {@code try { engine.getPlugins().add(new Plugin()); }
 * catch (Exception e) { Log.e(...); }}, so a plugin that throws in its constructor or in {@code
 * onAttachedToEngine} is logged and registration still reports success. This guard validates the exact
 * pinned generator output and rewrites only those per-plugin catch wrappers into the bare {@code add}
 * statement, which makes the first failing plugin fail {@code registerWith}. The plugin list, its order
 * and the plugin classes stay exactly what Flutter generated; nothing is maintained by hand.
 *
 * <p>Every unsupported input - a different Flutter version, a changed generator template, a missing or
 * malformed registrant, a partly instrumented registrant, an unexpected statement - fails the build
 * instead of degrading to an admission that cannot be trusted.
 */
public final class GuardedPluginRegistration {
  /** The Flutter release whose generator template and registrant shape this guard was written against. */
  public static final String PINNED_FLUTTER_VERSION = "3.47.9";

  private static final String MESSAGE_PREFIX = "guarded plugin registration: ";

  private static final List<String> HEADER_LINES =
      List.of(
          "package io.flutter.plugins;",
          "",
          "import androidx.annotation.Keep;",
          "import androidx.annotation.NonNull;",
          "import io.flutter.Log;",
          "",
          "import io.flutter.embedding.engine.FlutterEngine;",
          "",
          "/**",
          " * Generated file. Do not edit.",
          " * This file is generated by the Flutter tool based on the",
          " * plugins that support the Android platform.",
          " */",
          "@Keep",
          "public final class GeneratedPluginRegistrant {",
          "  private static final String TAG = \"GeneratedPluginRegistrant\";",
          "  public static void registerWith(@NonNull FlutterEngine flutterEngine) {");

  private static final String HEADER = String.join("\n", HEADER_LINES);

  private static final String FOOTER = "  }\n}\n";

  private static final List<String> TEMPLATE_LINES =
      List.of(
          "package io.flutter.plugins;",
          "",
          "import androidx.annotation.Keep;",
          "import androidx.annotation.NonNull;",
          "import io.flutter.Log;",
          "",
          "import io.flutter.embedding.engine.FlutterEngine;",
          "",
          "/**",
          " * Generated file. Do not edit.",
          " * This file is generated by the Flutter tool based on the",
          " * plugins that support the Android platform.",
          " */",
          "@Keep",
          "public final class GeneratedPluginRegistrant {",
          "  private static final String TAG = \"GeneratedPluginRegistrant\";",
          "  public static void registerWith(@NonNull FlutterEngine flutterEngine) {",
          "{{#methodChannelPlugins}}",
          "  {{#supportsEmbeddingV2}}",
          "    try {",
          "      flutterEngine.getPlugins().add(new {{package}}.{{class}}());",
          "    } catch (Exception e) {",
          "      Log.e(TAG, \"Error registering plugin {{name}}, {{package}}.{{class}}\", e);",
          "    }",
          "  {{/supportsEmbeddingV2}}",
          "{{/methodChannelPlugins}}",
          "  }",
          "}");

  private static final String PINNED_TEMPLATE = "\n" + String.join("\n", TEMPLATE_LINES) + "\n";

  private static final String TEMPLATE_MARKER =
      "const _androidPluginRegistryTemplateNewEmbedding = '''";

  private static final String TEMPLATE_TOOL_PATH =
      "packages/flutter_tools/lib/src/flutter_plugins.dart";

  private static final Pattern FRAMEWORK_VERSION =
      Pattern.compile("\"frameworkVersion\"\\s*:\\s*\"([^\"]+)\"");

  private static final String TRY_LINE = "    try {";

  private static final String CATCH_LINE = "    } catch (Exception e) {";

  private static final String BLOCK_END_LINE = "    }";

  private static final String ADD_PREFIX = "      flutterEngine.getPlugins().add(new ";

  private static final String ADD_SUFFIX = "());";

  private static final String LOG_PREFIX = "      Log.e(TAG, \"Error registering plugin ";

  private static final Pattern PLUGIN_CLASS =
      Pattern.compile("[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)+");

  private static final Pattern PLUGIN_NAME = Pattern.compile("[a-z0-9_]+");

  private GuardedPluginRegistration() {}

  /** The exact generator template this guard supports, so a pin mismatch is visible in reviews. */
  public static String pinnedTemplate() {
    return PINNED_TEMPLATE;
  }

  /** Result of guarding one generated registrant. */
  public record Instrumented(String content, int pluginCount, boolean changed) {}

  /** A build failure caused by input this guard cannot verify. */
  public static final class GuardFailure extends RuntimeException {
    public GuardFailure(String message) {
      super(message);
    }
  }

  /**
   * Validates and, when needed, rewrites the generated registrant in place. Returns the number of
   * generated plugin blocks the rewritten source makes observable.
   */
  public static int guard(Path registrant, Path flutterSdk) {
    verifyFlutterSdk(flutterSdk);
    if (!Files.isRegularFile(registrant)) {
      throw fail(
          "the generated registrant is missing at "
              + registrant
              + "; run the Flutter tool (flutter build/run) so it generates the authoritative plugin list");
    }
    String content;
    try {
      content = Files.readString(registrant, StandardCharsets.UTF_8);
    } catch (MalformedInputException error) {
      throw fail("the generated registrant is not readable UTF-8: " + registrant);
    } catch (IOException error) {
      throw fail("the generated registrant could not be read at " + registrant + ": " + error);
    }
    Instrumented instrumented = instrument(content);
    if (instrumented.changed()) {
      write(registrant, instrumented.content());
    }
    return instrumented.pluginCount();
  }

  /** Validates the pinned Flutter SDK version and its Android generator template. */
  public static void verifyFlutterSdk(Path flutterSdk) {
    Path versionFile = flutterSdk.resolve("bin/cache/flutter.version.json");
    if (!Files.isRegularFile(versionFile)) {
      throw fail("the pinned Flutter SDK is not recognisable: missing " + versionFile);
    }
    Matcher version = FRAMEWORK_VERSION.matcher(read(versionFile));
    if (!version.find()) {
      throw fail("the Flutter SDK version file has no frameworkVersion: " + versionFile);
    }
    String found = version.group(1);
    if (!PINNED_FLUTTER_VERSION.equals(found)) {
      throw fail(
          "unsupported Flutter version "
              + found
              + " at "
              + flutterSdk
              + "; this guard is pinned to the "
              + PINNED_FLUTTER_VERSION
              + " Android plugin generator and must be reviewed before the SDK changes");
    }
    Path templateTool = flutterSdk.resolve(TEMPLATE_TOOL_PATH);
    if (!Files.isRegularFile(templateTool)) {
      throw fail("the Flutter Android plugin generator source is missing: " + templateTool);
    }
    String generatorSource = read(templateTool);
    int marker = generatorSource.indexOf(TEMPLATE_MARKER);
    if (marker < 0) {
      throw fail(
          "the Flutter Android plugin-registration template is not recognisable in " + templateTool);
    }
    int templateStart = marker + TEMPLATE_MARKER.length();
    int templateEnd = generatorSource.indexOf("'''", templateStart);
    if (templateEnd < 0) {
      throw fail("the Flutter Android plugin-registration template is unterminated in " + templateTool);
    }
    String template = generatorSource.substring(templateStart, templateEnd);
    if (!PINNED_TEMPLATE.equals(template)) {
      throw fail(
          "the Flutter Android plugin-registration template changed at "
              + describeFirstDifference(PINNED_TEMPLATE, template)
              + "; this guard only supports the "
              + PINNED_FLUTTER_VERSION
              + " template it was reviewed against");
    }
  }

  /**
   * Validates a generated registrant and returns its guarded form. Pure: no file access, so every
   * accepted and rejected shape is unit-testable.
   */
  public static Instrumented instrument(String generated) {
    if (!generated.startsWith(HEADER + "\n")) {
      throw fail(
          "unsupported generated registrant header at "
              + describeFirstDifference(HEADER + "\n", generated)
              + "; expected the pinned Flutter "
              + PINNED_FLUTTER_VERSION
              + " template");
    }
    if (!generated.endsWith(FOOTER)) {
      throw fail(
          "unsupported generated registrant footer in "
              + "the generated source; expected the pinned Flutter "
              + PINNED_FLUTTER_VERSION
              + " template closing braces");
    }

    String middle =
        generated.substring(HEADER.length() + 1, generated.length() - FOOTER.length());
    if (middle.isEmpty()) {
      throw fail("the generated registrant contains no generated plugin registrations");
    }
    if (!middle.endsWith("\n")) {
      throw fail(
          "unsupported generated registrant body: the last plugin block is not terminated by a newline");
    }
    List<String> lines = List.of(middle.substring(0, middle.length() - 1).split("\n", -1));

    List<String> guarded = new ArrayList<>();
    Set<String> pluginClasses = new LinkedHashSet<>();
    boolean sawRawBlock = false;
    boolean sawGuardedBlock = false;

    int index = 0;
    while (index < lines.size()) {
      String line = lines.get(index);
      if (TRY_LINE.equals(line)) {
        if (sawGuardedBlock) {
          throw fail(
              "the generated registrant is partly instrumented at line "
                  + (index + 1)
                  + "; every plugin block must be in the same form");
        }
        sawRawBlock = true;
        if (index + 4 >= lines.size()) {
          throw fail("the generated registrant ends inside a plugin block at line " + (index + 1));
        }
        String addLine = lines.get(index + 1);
        String pluginClass = pluginClassOf(addLine, index + 2);
        requireLine(lines, index + 2, CATCH_LINE);
        requireLogLine(lines, index + 3, pluginClass);
        requireLine(lines, index + 4, BLOCK_END_LINE);
        record(pluginClasses, pluginClass, index + 2);
        guarded.add(addLine);
        index += 5;
        continue;
      }

      if (line.startsWith(ADD_PREFIX)) {
        String pluginClass = pluginClassOf(line, index + 1);
        if (sawRawBlock) {
          throw fail(
              "the generated registrant is partly instrumented at line "
                  + (index + 1)
                  + "; every plugin block must be in the same form");
        }
        sawGuardedBlock = true;
        record(pluginClasses, pluginClass, index + 1);
        guarded.add(line);
        index++;
        continue;
      }

      throw fail(
          "unsupported generated registrant body at line "
              + (index + 1)
              + ": "
              + quote(line)
              + "; only the pinned Flutter per-plugin block shapes are accepted");
    }

    String content = HEADER + "\n" + String.join("\n", guarded) + "\n" + FOOTER;
    return new Instrumented(content, pluginClasses.size(), !content.equals(generated));
  }

  private static String pluginClassOf(String line, int number) {
    if (!line.startsWith(ADD_PREFIX) || !line.endsWith(ADD_SUFFIX)) {
      throw fail(
          "unsupported plugin block at line "
              + number
              + ": "
              + quote(line)
              + "; expected a generated registration statement");
    }
    String pluginClass = line.substring(ADD_PREFIX.length(), line.length() - ADD_SUFFIX.length());
    if (!PLUGIN_CLASS.matcher(pluginClass).matches()) {
      throw fail(
          "unsupported plugin block at line "
              + number
              + ": "
              + quote(line)
              + "; expected one fully qualified plugin class");
    }
    return pluginClass;
  }

  private static void requireLine(List<String> lines, int index, String expected) {
    if (!expected.equals(lines.get(index))) {
      throw fail(
          "unsupported plugin block at line "
              + (index + 1)
              + ": "
              + quote(lines.get(index))
              + "; expected "
              + quote(expected));
    }
  }

  private static void requireLogLine(List<String> lines, int index, String pluginClass) {
    String line = lines.get(index);
    String suffix = ", " + pluginClass + "\", e);";
    if (!line.startsWith(LOG_PREFIX) || !line.endsWith(suffix)) {
      throw fail(
          "unsupported plugin block at line "
              + (index + 1)
              + ": "
              + quote(line)
              + "; expected the generator log line for "
              + pluginClass);
    }
    String name = line.substring(LOG_PREFIX.length(), line.length() - suffix.length());
    if (!PLUGIN_NAME.matcher(name).matches()) {
      throw fail(
          "unsupported plugin block at line "
              + (index + 1)
              + ": "
              + quote(line)
              + "; expected a generated plugin name");
    }
  }

  private static void record(Set<String> pluginClasses, String pluginClass, int number) {
    if (!pluginClasses.add(pluginClass)) {
      throw fail(
          "the generated registrant registers the duplicate plugin class "
              + pluginClass
              + " at line "
              + number
              + "; a duplicate would leave the engine with a skipped plugin");
    }
  }

  private static String describeFirstDifference(String expected, String actual) {
    List<String> expectedLines = List.of(expected.split("\n", -1));
    List<String> actualLines = List.of(actual.split("\n", -1));
    int shared = Math.min(expectedLines.size(), actualLines.size());
    for (int index = 0; index < shared; index++) {
      if (!expectedLines.get(index).equals(actualLines.get(index))) {
        return "line " + (index + 1) + " (expected " + quote(expectedLines.get(index)) + ", found "
            + quote(actualLines.get(index)) + ")";
      }
    }
    return "line "
        + (shared + 1)
        + " (expected "
        + (expectedLines.size() > shared ? quote(expectedLines.get(shared)) : "end of template")
        + ", found "
        + (actualLines.size() > shared ? quote(actualLines.get(shared)) : "end of template")
        + ")";
  }

  private static String quote(String line) {
    String single = line.replace("\n", "\\n");
    return single.length() > 120 ? "'" + single.substring(0, 117) + "...'" : "'" + single + "'";
  }

  private static String read(Path path) {
    try {
      return Files.readString(path, StandardCharsets.UTF_8);
    } catch (IOException error) {
      throw fail("could not read " + path + ": " + error);
    }
  }

  private static void write(Path target, String content) {
    Path temporary = null;
    try {
      temporary = Files.createTempFile(target.getParent(), "guarded-registrant", ".tmp");
      Files.writeString(temporary, content, StandardCharsets.UTF_8);
      try {
        Files.move(
            temporary,
            target,
            StandardCopyOption.REPLACE_EXISTING,
            StandardCopyOption.ATOMIC_MOVE);
      } catch (AtomicMoveNotSupportedException unsupported) {
        Files.move(temporary, target, StandardCopyOption.REPLACE_EXISTING);
      }
    } catch (IOException error) {
      throw fail("the generated registrant could not be rewritten at " + target + ": " + error);
    } finally {
      if (temporary != null) {
        try {
          Files.deleteIfExists(temporary);
        } catch (IOException ignored) {
          // The source only matters; a leftover temporary file fails the guard tests instead.
        }
      }
    }
  }

  private static GuardFailure fail(String message) {
    return new GuardFailure(MESSAGE_PREFIX + message);
  }
}
